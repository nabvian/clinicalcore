const DICTS = { en, hi, bn };
let current = 'en';

export function setLanguage(lang) {
  current = DICTS[lang] ? lang : 'en';
  document.documentElement.lang = current;
}

export function language() {
  return current;
}

function fill(template, args) {
  return args.reduce((text, arg, i) => {
    const value = typeof arg === 'string' && arg.startsWith('item.') ? (DICTS[current][arg] ?? en[arg] ?? arg) : arg;
    return text.replaceAll(`{${i}}`, value);
  }, template);
}

export function t(key, ...args) {
  return fill(DICTS[current][key] ?? en[key] ?? key, args);
}

export function message(entry) {
  const template = current === 'en' ? null : DICTS[current][entry.code];
  return template ? fill(template, entry.args) : entry.message;
}

export function flagText(flag) {
  const title = current === 'en' ? flag.title : t(`flag.${flag.code}.title`, ...flag.args);
  const detail = current === 'en' ? flag.detail : t(flag.detail_key, ...flag.detail_args);
  return { title, detail };
}

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-label]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nLabel)); });
}
